/**
 * Счётчик Яндекс.Метрики: разбор номера из окружения.
 *
 * Отдельным модулем — чтобы проверка была под тестом. Внутри загрузчика
 * (`+layout.server.ts`) она бы жила строкой, которую нельзя прогнать: тот
 * читает `$env/dynamic/private` и без рантайма SvelteKit не запускается.
 */

/**
 * Номер счётчика, годный к подстановке в <script>, либо пустая строка.
 *
 * Только цифры, и это не паранойя ради паранойи: номер уезжает ВНУТРЬ тела
 * скрипта, поэтому любой символ помимо цифры оттуда исполнится в браузере
 * каждого посетителя. Значение приходит из нашего же `.env`, но правило
 * «данные не выполняются» не зависит от того, кому мы доверяем: опечатка в
 * `.env` не должна превращаться в исполняемый код.
 *
 * Пустая строка означает «счётчика нет» — и это штатное состояние стенда.
 * Вшитый в код номер собирал бы в статистику наши собственные прогоны, а на
 * первых неделях, когда живых посетителей единицы, посещаемость состояла бы
 * из проверок.
 */
export function metrikaId(raw: string | undefined | null): string {
  const v = (raw ?? '').trim();
  return /^\d{1,12}$/.test(v) ? v : '';
}
