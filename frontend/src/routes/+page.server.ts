import { redirect } from '@sveltejs/kit';
import type { PageServerLoad } from './$types';
import { DEFAULT_CITY_SLUG } from '$lib/api';

/**
 * Корень переехал на страницу города.
 *
 * 308, а не 302: адрес сменился навсегда, и поисковик обязан перенести на
 * `/msk` вес, накопленный главной. Временный редирект оставил бы вес на «/» и
 * держал бы в индексе две страницы с одинаковым содержимым. 308 (а не 301)
 * потому, что он сохраняет метод — на GET-странице это ничего не меняет, но
 * не даёт браузеру превратить будущий POST в GET.
 *
 * Своего +page.svelte у корня больше нет: load редиректит всегда, рисовать
 * нечего, а оставленный компонент был бы мёртвым кодом, который однажды
 * покажется кому-то живой главной.
 */
export const load: PageServerLoad = () => {
	redirect(308, `/${DEFAULT_CITY_SLUG}`);
};
