import { error } from '@sveltejs/kit';
import type { PublicEvent } from '$lib/types';
import type { Section } from '$lib/taxonomy';
import { listingMeta, type City, type MetaTags } from '$lib/seo';
import {
  ApiError,
  FALLBACK_CITY,
  PAGE_SIZE,
  RUNNING_PREVIEW,
  getEvents,
  getFacets,
  queryForSection,
  type EventKind,
  type Facets,
  type WhenFacets
} from '$lib/api';

/**
 * Общая загрузка страницы города и страницы раздела.
 *
 * Один файл на два маршрута намеренно: они отличаются РОВНО одним аргументом
 * (раздел), а разъезжаются такие пары мгновенно — стоит поправить обработку
 * отказа в одном месте и забыть про второе, и одна из двух страниц начнёт
 * молча врать. Файл лежит в каталоге маршрута и роутером не подхватывается:
 * SvelteKit считает страницами только файлы с «+».
 */
export interface ListingData {
  origin: string;
  city: City;
  facets: Facets | null;
  /**
   * false — часть счётчиков занижена: один из сторов молчал при подсчёте.
   * Тогда цифры не рисуются вовсе. Ноль в разделе читается человеком как
   * «сегодня ничего нет», и такое утверждение мы делать не вправе.
   */
  countsTrusted: boolean;
  section: Section | null;
  /** Выбранная полоса; null — обе. */
  kind: EventKind | null;
  featured: PublicEvent[];
  /** Основная полоса: при kind=null это «по дате и времени». */
  events: PublicEvent[];
  /** total ОСНОВНОЙ полосы. */
  total: number;
  /** Вторая полоса — только при kind === null. Иначе null. */
  running: { events: PublicEvent[]; total: number } | null;
  /**
   * Бэкенд действительно разложил доску по полосам.
   *
   * false бывает ровно в одном случае — фронт выкатился раньше бэкенда, и
   * старый бэкенд `kind` игнорирует, отдавая на любой запрос ОДНУ И ТУ ЖЕ
   * доску. Тогда полос не существует: вторая уже погашена (`running === null`),
   * а переключатель показывать нельзя — обе пилюли вели бы на выдачу, не
   * отличимую от самой доски, с кодом 200 и без единой строки в логах.
   *
   * Признак — разрез по полосам в ответе фасетов (у старого бэкенда ключа нет
   * вовсе), а при мёртвых фасетах — поле `kind` у карточек. По ПУСТОМУ списку
   * судить нельзя: пустая полоса у исправного бэкенда законна.
   */
  laneSplit: boolean;
  /**
   * Числа для пилюль переключателя — тоталы двух полос ЭТОЙ страницы.
   *
   * `null` означает «числа нет»: второй полосы не спрашивали (выбрана одна),
   * она не ответила, или список приехал с молчащим источником и его total
   * занижен. Тогда ряд рисуется без цифр — правило то же, что у countsTrusted.
   *
   * Из фасетов эти числа взять НЕЛЬЗЯ: фасеты просятся без фильтра раздела,
   * поэтому их разрез по полосам — число по всему городу, а пилюля ведёт в
   * раздел. На `/msk/concert` это обещало бы «ИДЁТ СЕЙЧАС · 88» и открывало
   * пустую сетку — тот же класс, что подпись «СОБЫТИЯ · 90 ИЗ 150»: число
   * рядом с элементом есть обещание того, что по нему откроется.
   */
  laneCounts: { timed: number; running: number } | null;
  /** Сколько всего на доске/в разделе, обе полосы. Для подписи и меты. */
  grandTotal: number;
  meta: MetaTags;
  /** Путь, а не абсолютный адрес: ссылка в разметке обязана остаться своей. */
  crumbs: { name: string; path: string }[];
}

const KINDS = new Set<string>(['running', 'timed']);

/**
 * Полоса из адресной строки.
 *
 * Неизвестное значение — 404, а не молчаливый сброс на «обе полосы». Правило
 * то же, что у бэкенда (`kind=junk` → 400) и по той же причине: сброс
 * выглядит успехом. Страница отвечает 200 с полной доской, человек читает её
 * как выдачу своего фильтра, а робот получает ещё один адрес-дубль с тем же
 * содержимым. Отказ, который выглядит успехом, дороже отказа.
 *
 * Пустое значение (`?kind=`) — это НЕ ошибка: так же его читает бэкенд
 * («параметр не задан»), и ссылка, собранная с пустым параметром, обязана
 * вести на обе полосы, а не в 404.
 *
 * Разбор живёт здесь, а не в каждом `+page.server.ts`, по той же причине, по
 * которой здесь лежит `loadListing`: две копии одного правила на двух
 * маршрутах расходятся молча.
 */
export function kindFromSearch(params: URLSearchParams): EventKind | null {
  const raw = params.get('kind');
  if (raw === null || raw === '') return null;
  if (!KINDS.has(raw)) error(404, 'Такой полосы нет');
  return raw as EventKind;
}

/**
 * Сколько всего событий на ЭТОЙ странице обеими полосами — из городских
 * фасетов.
 *
 * Каждое число берётся из СВОЕГО разреза, и ни одно — из разреза по полосам.
 * У доски города это `total`, у раздела — рубрика в `categories`,
 * «сегодня/завтра/выходные» в `when`, «бесплатно» в `free`. Все они считаются
 * без условия `kind` (см. CountFacets в backend/internal/events/filter.go),
 * то есть по обеим полосам сразу, и приезжают от бэкенда любого возраста.
 *
 * Сумма `kind.running + kind.timed` дала бы то же число на доске города — и
 * ровно она превращала «полос не посчитали» в «событий нет»: `/msk?kind=running`
 * в день без идущих подписывался «Афиша Москвы · 0 событий», то же уезжало в
 * мету и в пустой ItemList разметки, а заголовок кэша разрешал раздавать это
 * полчаса. `total` от раскладки по полосам не зависит вовсе — значит и число
 * доски перестаёт от неё зависеть.
 *
 * Разрез по полосам сюда не годится и по второй причине: фасеты просятся БЕЗ
 * фильтра раздела (иначе плитка категорий схлопнулась бы в одну строку),
 * поэтому в разделе он говорит про город, а не про раздел.
 *
 * null означает «числа нет» — тогда вызывающий берёт total своей полосы:
 * заниженное число честнее чужого.
 */
function bothLanesTotal(facets: Facets | null, section: Section | null): number | null {
  if (!facets) return null;
  if (!section) return facets.total;
  if (section.kind === 'category') {
    return facets.categories.find((c) => c.code === section.code)?.count ?? null;
  }
  if (section.kind === 'when') {
    return facets.when[section.code as keyof WhenFacets] ?? null;
  }
  return facets.free;
}

export async function loadListing(opts: {
  fetch: typeof globalThis.fetch;
  origin: string;
  citySlug: string;
  section: Section | null;
  kind: EventKind | null;
}): Promise<ListingData> {
  const { fetch, origin, citySlug, section, kind } = opts;
  // Тот же адрес по умолчанию, что у остальных загрузчиков этого фронта:
  // в бою его всегда задаёт compose, менять умолчание в одном файле из
  // четырёх — верный способ получить расхождение стендов.
  const backend = process.env.BACKEND_INTERNAL_URL ?? 'http://localhost:3003';
  // База для api.ts включает /api — в браузере она вшита Vite ровно такой
  // (https://afisha.vshage.app/api), а BACKEND_INTERNAL_URL указывает на
  // корень сервиса. Забыть здесь /api значит получить 404 на каждый запрос
  // при полностью живом бэкенде, причём страница при этом отвечает 200 с
  // пустой лентой — отказ немой.
  const base = `${backend}/api`;
  const query = queryForSection(citySlug, section);

  // Полосы просим ПО ОТДЕЛЬНОСТИ, а не режем один список на клиенте: у
  // каждой полосы свой порядок (идущие — по концу, «успею ли»), свой total и
  // своё «показать ещё». Разрезание общей выдачи дало бы двенадцать идущих
  // из первой сотни вместо двенадцати ближайших к закрытию.
  const wantRunning = kind === null;

  // Список, вторая полоса и фасеты — параллельно, и отказы разбираются ПО
  // ОТДЕЛЬНОСТИ: фасеты это счётчики, вторая полоса это превью, а основной
  // список — сам продукт. Мёртвые счётчики не повод не показать ленту.
  const [listRes, runningRes, facetsRes] = await Promise.allSettled([
    getEvents(fetch, { ...query, kind: kind ?? 'timed', limit: PAGE_SIZE, offset: 0 }, base),
    wantRunning
      ? getEvents(fetch, { ...query, kind: 'running', limit: RUNNING_PREVIEW, offset: 0 }, base)
      : Promise.resolve(null),
    getFacets(fetch, citySlug, base)
  ]);

  if (listRes.status === 'rejected') {
    const reason = listRes.reason;
    // 400 на списке означает, что словарь разделов фронта и словарь бэкенда
    // разъехались: матчер пропустил слаг, которого бэкенд не знает. Человеку
    // честнее 404, чем пустая лента, а причину читает оператор в stdout.
    if (reason instanceof ApiError && reason.status === 400) {
      console.error(
        'afisha: бэкенд отверг параметры раздела — словари разъехались:',
        JSON.stringify({ ...query, kind: kind ?? 'timed' }),
        reason.message
      );
      error(404, 'Такого раздела нет');
    }
    // Любой другой отказ — это «источники молчат», а не «событий нет».
    // Подставить пустую ленту значило бы отдать 200 с честной на вид доской:
    // подпись «ВСЕ СОБЫТИЯ · 0», описание «0 событий с датами, местами и
    // ценами» в мете и пустой ItemList в разметке — то есть мы бы СКАЗАЛИ
    // роботу, что в Москве сегодня ничего нет, и заголовок кэша разрешил бы
    // раздавать это полчаса. 503 честен ровно в ту сторону, в какую нужно:
    // и человек, и робот понимают «приходи позже», страница ошибки не несёт
    // ни разметки, ни успешного кэша. Логи прода в Loki не доезжают, поэтому
    // строка выше — единственный след, и она обязана остаться.
    console.error('afisha: список событий не ответил:', reason);
    error(503, 'Лента временно недоступна');
  }
  if (runningRes.status === 'rejected') {
    // Полоса «идёт сейчас» — ВТОРАЯ полоса, а не продукт. Уронить доску
    // города из-за превью двенадцати карточек было бы хуже того отказа, ради
    // которого 503 и заведён: основная лента уже приехала, и человек за ней
    // и пришёл. Поэтому полоса просто не рисуется, а причина уходит в stdout
    // — иначе исчезнувшая полоса выглядит как «сегодня ничего не идёт», а
    // это утверждение мы делать не вправе (тот же довод, что у фасетов).
    console.error('afisha: полоса «идёт сейчас» не ответила, рисую без неё:', runningRes.reason);
  }
  if (facetsRes.status === 'rejected') {
    // Молча подставить нули нельзя: страница выглядела бы здоровой, а плитка
    // и «быстрый выбор» исчезли бы без объяснения. Строка в stdout — то, на
    // что можно повесить смок.
    console.error('afisha: фасеты не ответили, страница без счётчиков:', facetsRes.reason);
  }

  const list = listRes.status === 'fulfilled' ? listRes.value : { featured: [], all: [], total: 0 };
  const runningList = runningRes.status === 'fulfilled' ? runningRes.value : null;
  let facets = facetsRes.status === 'fulfilled' ? facetsRes.value : null;
  const city: City = facets?.city ?? { ...FALLBACK_CITY, slug: citySlug };

  // Знает ли бэкенд полосы ВООБЩЕ.
  //
  // Фронт и бэкенд — два образа, и порядок выката не гарантирован. Старый
  // бэкенд параметр `kind` просто игнорирует: на оба запроса он отдаёт ОДНУ И
  // ТУ ЖЕ доску, и полоса «идёт сейчас» стала бы копией верхушки основной —
  // задвоение на публичной доске, с кодом 200 и без единой строки в логах.
  //
  // Спрашиваем САМ ОТВЕТ, а не версию образа: версия у нас нигде не
  // объявлена. Главный признак — разрез по полосам в фасетах: он есть у
  // нового бэкенда ВСЕГДА, независимо от наполнения доски (пустая полоса
  // приезжает как `"kind":{"running":0,"timed":0}`), а старый ключа не шлёт
  // вовсе. Поэтому `normalizeFacets` и обязан различать отсутствие и нули.
  //
  // Признак по карточкам остаётся ВТОРЫМ, через `||`: фасеты умеют не
  // ответить совсем, и тогда полосы всё равно опознаются. В одиночку он
  // непригоден — по пустому списку он отвечает «бэкенд старый», хотя пустая
  // полоса у исправного бэкенда законна: в разделе может не идти ничего, а
  // при `kind !== null` второго списка не спрашивали вовсе. Так `?kind=running`
  // в день без идущих гасил переключатель, и вернуться в соседнюю полосу
  // было нечем, кроме кнопки «назад».
  const qTagged = (evs: PublicEvent[]) => evs.length > 0 && evs.every((e) => e.kind !== undefined);
  const laneSplit =
    facets?.kind !== undefined || qTagged(list.all) || qTagged(runningList?.all ?? []);

  // Вторая полоса рисуется, только когда раскладка настоящая И присланное в
  // ней действительно идущее. Пустой список это условие проходит (у `every`
  // пустое множество истинно) — пустая полоса законна и гасится уже показом.
  const runningLane =
    laneSplit && runningList && runningList.all.every((e) => e.kind === 'running')
      ? { events: runningList.all, total: runningList.total }
      : null;

  // Активная рубрика обязана быть в плитке, даже когда бэкенд её не прислал:
  // фасеты несут только count > 0, а раздел с нулём событий — адрес живой,
  // матчер его пропускает. Без этой вставки на пустом разделе подсвечивать
  // нечего, и человек не понимает, где он находится.
  //
  // Число берём по обеим полосам: плитка ведёт на раздел целиком, а не на
  // выбранную полосу.
  const laneTotal = list.total;
  const bothLanes = runningLane ? laneTotal + runningLane.total : laneTotal;
  if (
    facets &&
    section?.kind === 'category' &&
    !facets.categories.some((c) => c.code === section.code)
  ) {
    facets = {
      ...facets,
      categories: [...facets.categories, { code: section.code, count: bothLanes }]
    };
  }

  // Сколько всего на этой странице обеими полосами.
  //
  // Когда обе полосы приехали, сумма известна точно и считается по ним —
  // фасеты для этого не нужны и могут быть мертвы. Когда выбрана одна полоса
  // (или вторая не ответила), число обеих берётся из своего разреза фасетов —
  // у доски города это `total`, посчитанный без условия полосы, — а если
  // фасетов нет вовсе, остаётся total полосы. Заниженное число тут честнее
  // выдуманного: им подписывается заголовок «Афиша Москвы · N событий», и
  // «N событий» на `?kind=running` должно говорить про город, а не про полосу.
  const grandTotal = runningLane
    ? laneTotal + runningLane.total
    : (bothLanesTotal(facets, section) ?? laneTotal);

  // Числа для пилюль — тоталы полос ЭТОЙ страницы, и только они: числа
  // фасетов относятся к городу целиком, а пилюля ведёт в раздел.
  //
  // Известны они ровно тогда, когда обе полосы спрошены и обе ответили. Не
  // спрашивали вторую (выбрана одна полоса) или она не ответила — числа нет,
  // и подставлять на его место городское нельзя. Молчащий источник в ответе
  // списка занижает его total ровно так же, как занижает счётчики фасетов, —
  // заниженное число выглядит достоверным, поэтому и здесь оно не рисуется.
  const laneCounts =
    runningLane && !list.degraded?.length && !runningList?.degraded?.length
      ? { timed: laneTotal, running: runningLane.total }
      : null;

  const meta = listingMeta({
    origin,
    city,
    // В мете — число обеих полос: канонический адрес у полос общий, и
    // описание относится к нему, а не к выбранному разрезу.
    total: grandTotal,
    heading: section?.heading,
    blurb: section?.blurb,
    sectionSlug: section?.slug,
    kind
  });

  const crumbs = [{ name: `Афиша ${city.of}`, path: `/${city.slug}` }];
  if (section) crumbs.push({ name: section.tile, path: `/${city.slug}/${section.slug}` });

  // Неполные счётчики не показываем вовсе. Правило уже сформулировано в
  // FilterRow: «неверное число хуже отсутствующего» — ноль в разделе значит
  // «сегодня ничего нет», и это может быть ложью. Плитка при этом остаётся:
  // раздел без цифры ведёт туда же, куда вёл.
  const countsTrusted = !facets?.degraded?.length;

  return {
    origin,
    city,
    facets,
    countsTrusted,
    section,
    kind,
    // Закрепление относится к доске города ЦЕЛИКОМ — не к разделу и не к
    // полосе. В шапке раздела закреплённое событие другой рубрики было бы
    // ложью, а над полосой «идёт сейчас» висело бы точечное событие, то есть
    // карточка не из той полосы, в которую человек нажал. Список исключений
    // подрос на полосу, само правило прежнее.
    //
    // Бэкенд закреплённое отдаёт и при `kind=timed`: полоса не входит в
    // Filter.IsEmpty (§3.1) — иначе запрос основной полосы обнулил бы
    // featured, и герой исчез бы с главной молча. Решает это одно условие
    // здесь, а не лишний запрос туда.
    featured: section || kind ? [] : list.featured,
    events: list.all,
    total: laneTotal,
    running: runningLane,
    laneSplit,
    laneCounts,
    grandTotal,
    meta,
    crumbs
  };
}
