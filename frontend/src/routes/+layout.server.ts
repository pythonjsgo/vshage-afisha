import { env } from '$env/dynamic/private';
import type { LayoutServerLoad } from './$types';
import { metrikaId } from '$lib/analytics';

/**
 * Метки владения сайтом для Яндекс.Вебмастера и Google Search Console.
 *
 * Почему из ОКРУЖЕНИЯ, а не строкой в разметке. Токен выдаётся в личном
 * кабинете фаундера и до этого момента неизвестен; строка в коде означала бы
 * пересборку образа и полный цикл выкатки ради двух случайных хешей. Через
 * `$env/dynamic/private` значение читается на каждый запрос: положил в .env
 * хоста, перезапустил контейнер — метка на месте.
 *
 * Почему в КОРНЕВОЙ раскладке, то есть на каждой странице. Проверка ходит на
 * корень ресурса, а корень у нас отвечает 308 на /msk. Метка, живущая только
 * на одной странице, зависела бы от того, идёт ли робот проверки по редиректу,
 * — а это его внутреннее дело, которым мы не управляем. На каждой странице
 * метка стоит два десятка байт и не зависит ни от чего.
 *
 * Пустая строка = метки нет: шапка не рисует тег вовсе. Тег с пустым
 * содержимым проверку не проходит, зато выглядит как настроенный — ровно тот
 * вид отказа, который потом ищут часами.
 */
export const load: LayoutServerLoad = () => ({
  verification: {
    yandex: env.YANDEX_VERIFICATION?.trim() ?? '',
    google: env.GOOGLE_SITE_VERIFICATION?.trim() ?? ''
  },
  metrikaId: metrikaId(env.YANDEX_METRIKA_ID)
});
