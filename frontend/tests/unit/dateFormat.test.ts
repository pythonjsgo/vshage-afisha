import { describe, it, expect } from 'vitest';
import { formatEventDate, formatEventDateLong, formatEndDate, formatWhen } from '../../src/lib/dateFormat';

/**
 * Даты в фикстурах — с ЯВНЫМ смещением. Прежние строки вида
 * '2026-04-25T19:00:00' парсятся как ЛОКАЛЬНОЕ время рантайма, а старый
 * форматтер печатал тоже в локальном — две ошибки сокращались, и тест
 * проходил в любой зоне, ничего при этом не проверяя. Именно поэтому он не
 * поймал, что SSR-контейнер (UTC) рисует всю афишу в UTC.
 *
 * Теперь утверждение честное: событие в 19:00 по Москве обязано печататься
 * как 19:00 независимо от того, где выполняется код.
 */
const now = new Date('2026-04-25T10:00:00+03:00');

describe('formatEventDate', () => {
  it('сегодня', () => {
    expect(formatEventDate('2026-04-25T19:00:00+03:00', now)).toBe('СЕГОДНЯ В 19:00');
  });
  it('завтра', () => {
    expect(formatEventDate('2026-04-26T19:00:00+03:00', now)).toBe('ЗАВТРА В 19:00');
  });
  it('дальше по календарю', () => {
    expect(formatEventDate('2026-05-15T19:00:00+03:00', now)).toBe('15 МАЯ · 19:00');
  });

  // Ровно тот случай, ради которого зона задана явно: полночь по Москве в
  // рантайме UTC — это 21:00 ПРЕДЫДУЩЕГО дня. Старый форматтер печатал
  // «31 АВГ · 21:00» в разметке, которую видят краулер и превью в телеге,
  // а после гидрации в московском браузере текст менялся на «1 СЕН».
  it('полночь по Москве не уезжает на день назад', () => {
    const out = formatEventDate('2026-09-01T00:00:00+03:00', now, false);
    expect(out).toBe('1 СЕН');
    expect(out).not.toContain('31');
  });

  // «Времени нет» — частый случай у импортированных анонсов (7 карточек из
  // 20 на замере 30.08). Печатать там 00:00 значило бы выдумывать время.
  it('без времени печатает только дату', () => {
    expect(formatEventDate('2026-05-15T00:00:00+03:00', now, false)).toBe('15 МАЯ');
    expect(formatEventDate('2026-04-26T00:00:00+03:00', now, false)).toBe('ЗАВТРА');
  });
});

describe('formatEventDateLong', () => {
  it('с месяцем', () => {
    expect(formatEventDateLong('2026-04-25T19:30:00+03:00')).toBe('25 АПР · 19:30');
  });
  it('без времени', () => {
    expect(formatEventDateLong('2026-04-25T00:00:00+03:00', false)).toBe('25 АПР');
  });
});

describe('formatEndDate', () => {
  it('конец многодневной программы', () => {
    expect(formatEndDate('2026-09-13T23:59:00+03:00')).toBe('до 13 СЕН');
  });
});

/* ------------------------------------------------------------------------ *
 *  formatWhen — одна подпись на все виды события
 * ------------------------------------------------------------------------ */

/**
 * Фикстура события: только те поля, которые читает подпись. Префикс `w` — у
 * зоны свой, чтобы два строителя одной волны не объявили одноимённый хелпер
 * в общем пакете (уже ломало компиляцию тестов 02.09).
 */
function wEv(p: Partial<Parameters<typeof formatWhen>[0]>): Parameters<typeof formatWhen>[0] {
  return { start_time: '2026-09-12T19:00:00+03:00', kind: 'timed', ...p };
}

/** 12 сентября 2026, 10:00 по Москве. Все ожидания ниже отсчитываются отсюда. */
const wNow = new Date('2026-09-12T10:00:00+03:00');

/**
 * Выполнить тело в заданной зоне рантайма и вернуть зону обратно.
 *
 * Нужно ровно за одним: доказать, что подпись НЕ считает дни в зоне
 * процесса. SSR-контейнер афиши живёт в UTC, и наивная реализация на
 * getDate() там отвечает про вчера — этот класс ошибки уже уводил «1 сентября
 * 00:00 МСК» в разметку как «31 АВГ».
 */
function wUnderTZ<T>(tz: string, body: () => T): T {
  const was = process.env.TZ;
  process.env.TZ = tz;
  try {
    return body();
  } finally {
    process.env.TZ = was;
  }
}

describe('formatWhen — точечное событие', () => {
  // Первая строка таблицы контракта: у точечного подпись обязана остаться
  // ровно той, что была, — иначе правка полос переписала бы 172 карточки
  // ленты, к полосам отношения не имеющие.
  it('сегодня со временем', () => {
    expect(formatWhen(wEv({}), wNow).text).toBe('СЕГОДНЯ В 19:00');
  });
  it('другой день со временем', () => {
    const ev = wEv({ start_time: '2026-09-20T19:00:00+03:00' });
    expect(formatWhen(ev, wNow).text).toBe('20 СЕН · 19:00');
  });
  it('без времени — только дата', () => {
    const ev = wEv({ start_time: '2026-09-20T00:00:00+03:00', start_time_known: false });
    expect(formatWhen(ev, wNow).text).toBe('20 СЕН');
  });
  it('точечное никогда не срочное', () => {
    expect(formatWhen(wEv({}), wNow).urgent).toBe(false);
  });

  /**
   * Старый ответ бэкенда — тот, что отдаёт PROD прямо сейчас: ни kind, ни
   * multiday, ни open_ended в нём нет. Подпись обязана работать как раньше,
   * а не рисовать пустую строку: фронт выкатывается отдельно от бэкенда, и
   * между двумя выкатками эта ветка — единственная живая.
   */
  it('старый payload без kind/multiday читается как точечное', () => {
    const ev = { start_time: '2026-09-12T19:00:00+03:00' };
    expect(formatWhen(ev, wNow).text).toBe('СЕГОДНЯ В 19:00');
  });
});

describe('formatWhen — идущая программа', () => {
  const wRunning = (p: Partial<Parameters<typeof formatWhen>[0]>) =>
    wEv({ kind: 'running', multiday: true, actual_start_date: '2026-03-01', ...p });

  it('бессрочная', () => {
    const out = formatWhen(wRunning({ open_ended: true }), wNow);
    expect(out).toEqual({ text: 'ИДЁТ ПОСТОЯННО', urgent: false });
  });

  it('кончается сегодня — последний день, срочно', () => {
    const out = formatWhen(wRunning({ end_time: '2026-09-12T21:00:00+03:00' }), wNow);
    expect(out).toEqual({ text: 'ПОСЛЕДНИЙ ДЕНЬ', urgent: true });
  });

  it('осталось 1–3 дня — со склонением, срочно', () => {
    const day = (iso: string) => formatWhen(wRunning({ end_time: iso }), wNow);
    expect(day('2026-09-13T21:00:00+03:00')).toEqual({ text: 'ОСТАЛОСЬ 1 ДЕНЬ', urgent: true });
    expect(day('2026-09-14T21:00:00+03:00')).toEqual({ text: 'ОСТАЛОСЬ 2 ДНЯ', urgent: true });
    expect(day('2026-09-15T21:00:00+03:00')).toEqual({ text: 'ОСТАЛОСЬ 3 ДНЯ', urgent: true });
  });

  it('осталось больше трёх дней — дата конца, не срочно', () => {
    const out = formatWhen(wRunning({ end_time: '2026-09-20T21:00:00+03:00' }), wNow);
    expect(out).toEqual({ text: 'ИДЁТ ДО 20 СЕН', urgent: false });
  });

  /**
   * Обратный контроль к правилу про время у периода: на идущую программу оно
   * не разливается. `start_time` у неё СДВИНУТ на сегодня ради сортировки, так
   * что печатать оттуда час значило бы выдать выдуманное время за настоящее, а
   * настоящее время первого дня выставки, открывшейся в июне, человеку и не
   * нужно — он спрашивает «до когда».
   */
  it('у идущей программы времени нет, даже когда оно известно', () => {
    const cases = [
      wRunning({ start_time: '2026-09-12T19:30:00+03:00', end_time: '2026-09-20T21:00:00+03:00' }),
      wRunning({ start_time: '2026-09-12T19:30:00+03:00', end_time: '2026-09-12T21:00:00+03:00' }),
      wRunning({ start_time: '2026-09-12T19:30:00+03:00', open_ended: true })
    ];
    for (const ev of cases) expect(formatWhen(ev, wNow).text).not.toMatch(/\d\d:\d\d/);
  });

  /**
   * Главный запрет контракта. У идущих карточек `date` — чаще дата ПОСТА, а
   * не открытия: у биеннале, работающей с марта, в базе стоит 5 сентября.
   * Написать «идёт с 5 сентября» значило бы соврать от своего имени на
   * публичной доске. Полоса отвечает только на «до когда».
   */
  it('НИКОГДА не пишет «идёт с …»', () => {
    const cases = [
      wRunning({ open_ended: true }),
      wRunning({ end_time: '2026-09-12T21:00:00+03:00' }),
      wRunning({ end_time: '2026-09-14T21:00:00+03:00' }),
      wRunning({ end_time: '2026-09-20T21:00:00+03:00' })
    ];
    for (const ev of cases) {
      const t = formatWhen(ev, wNow).text;
      expect(t).not.toMatch(/ИДЁТ С\b/);
      expect(t).not.toContain('5 СЕН');
    }
  });
});

describe('formatWhen — период впереди', () => {
  const wAhead = (p: Partial<Parameters<typeof formatWhen>[0]>) =>
    wEv({ kind: 'timed', multiday: true, ...p });

  /**
   * КОНТРОЛЬ ко всем проверкам времени ниже: у события без известного часа
   * подпись остаётся голым периодом. Без него правило «всегда дописывай время»
   * прошло бы все четыре новых теста и стёрло различие, ради которого заведён
   * `start_time_known`: полночь в данных означает отсутствие времени, а не
   * начало ночью, и печатать там «· 00:00» значило бы выдумать час.
   *
   * Признак проставлен ЯВНО. Прежде эти фикстуры молчали о нём и полагались на
   * то, что подпись периода время не печатает вовсе; с появлением времени
   * такое умолчание проверяло бы не то, что написано в названии теста.
   */
  it('бессрочный впереди без времени — «с … , постоянно»', () => {
    const ev = wAhead({
      start_time: '2026-09-20T00:00:00+03:00',
      start_time_known: false,
      open_ended: true
    });
    expect(formatWhen(ev, wNow)).toEqual({ text: 'С 20 СЕН, ПОСТОЯННО', urgent: false });
  });

  it('в одном месяце без времени — месяц пишется один раз', () => {
    const ev = wAhead({
      start_time: '2026-09-15T00:00:00+03:00',
      start_time_known: false,
      end_time: '2026-09-20T21:00:00+03:00'
    });
    expect(formatWhen(ev, wNow)).toEqual({ text: '15 — 20 СЕН', urgent: false });
  });

  it('через границу месяца без времени — оба месяца', () => {
    const ev = wAhead({
      start_time: '2026-09-28T00:00:00+03:00',
      start_time_known: false,
      end_time: '2026-10-03T21:00:00+03:00'
    });
    expect(formatWhen(ev, wNow)).toEqual({ text: '28 СЕН — 3 ОКТ', urgent: false });
  });

  /**
   * Время начала известно — оно ОБЯЗАНО остаться в подписи.
   *
   * Замер по проду 07.09: 16 будущих многодневных карточек из первых двухсот
   * несут точный час, и это ровно те события, ради которых полоса «по дате и
   * времени» существует, — спектакль «Онегин. Я не договорила» 20:00, показы
   * «Ночи» Антониони 19:30, «Мой папа — Питер Пэн» 19:00, «Волшебные миры
   * Миядзаки» 19:00. Правило периода без часа стирало с них время, то есть
   * ломало ориентирование той же строкой, которая его чинила. Отбросить
   * данные, которые дал источник, — регрессия; напечатать их — в худшем
   * случае неточность, и период рядом её объясняет.
   */
  it('в одном месяце со временем — час остаётся', () => {
    const ev = wAhead({
      start_time: '2026-09-18T20:00:00+03:00',
      end_time: '2026-09-19T22:00:00+03:00'
    });
    expect(formatWhen(ev, wNow)).toEqual({ text: '18 — 19 СЕН · 20:00', urgent: false });
  });

  it('через границу месяца со временем — час остаётся', () => {
    const ev = wAhead({
      start_time: '2026-09-20T19:00:00+03:00',
      end_time: '2026-11-13T22:00:00+03:00'
    });
    expect(formatWhen(ev, wNow)).toEqual({ text: '20 СЕН — 13 НОЯ · 19:00', urgent: false });
  });

  it('бессрочный впереди со временем — час перед «постоянно»', () => {
    const ev = wAhead({ start_time: '2026-09-20T19:00:00+03:00', open_ended: true });
    expect(formatWhen(ev, wNow)).toEqual({ text: 'С 20 СЕН · 19:00, ПОСТОЯННО', urgent: false });
  });

  /**
   * Признак не задан вовсе — так приходят события кабинета, у которых поля
   * `start_time_known` нет в принципе. Час у них настоящий, и молчать о нём
   * нельзя: «не сказано, что времени нет» — это «время есть».
   */
  it('признак не задан — час считается известным', () => {
    const ev = wAhead({
      start_time: '2026-09-18T20:00:00+03:00',
      end_time: '2026-09-19T22:00:00+03:00'
    });
    expect(ev.start_time_known).toBeUndefined();
    expect(formatWhen(ev, wNow).text).toBe('18 — 19 СЕН · 20:00');
  });

  /**
   * Тот же день и месяц, но разные ГОДА — «12 — 20 СЕН» здесь было бы враньём
   * о годичной программе. Проверка стоит потому, что «совпал месяц» пишется
   * одним сравнением слишком легко.
   */
  it('через границу года месяц не схлопывается', () => {
    const ev = wAhead({
      start_time: '2026-09-15T00:00:00+03:00',
      // Признак задан явно по той же причине, что у соседей: тест говорит про
      // МЕСЯЦ, и час в ожидаемой строке увёл бы его в сторону.
      start_time_known: false,
      end_time: '2027-09-20T21:00:00+03:00'
    });
    expect(formatWhen(ev, wNow).text).toBe('15 СЕН — 20 СЕН');
  });
});

describe('formatWhen — дни считаются в МСК, а не в зоне рантайма', () => {
  /**
   * Контроль прибора. Если подмена зоны не сработала, тест ниже пройдёт на
   * любой реализации и будет измерять сам себя — а зелёное на сломанном
   * приборе хуже отсутствия проверки.
   */
  it('контроль: подмена зоны рантайма действует', () => {
    const d = new Date('2026-09-12T00:30:00+03:00');
    expect(wUnderTZ('UTC', () => d.getDate())).toBe(11);
    expect(wUnderTZ('Europe/Moscow', () => d.getDate())).toBe(12);
  });

  /**
   * Полпервого ночи по Москве — это ещё 11 сентября по UTC. Программа,
   * закрывающаяся 12-го, обязана читаться как «ПОСЛЕДНИЙ ДЕНЬ». Наивный счёт
   * в зоне процесса дал бы «ОСТАЛОСЬ 1 ДЕНЬ» — то есть пообещал бы человеку
   * лишние сутки на выставку, которая закрывается сегодня.
   */
  it('после полуночи МСК последний день остаётся последним', () => {
    const midnight = new Date('2026-09-12T00:30:00+03:00');
    const ev = wEv({
      kind: 'running',
      multiday: true,
      actual_start_date: '2026-03-01',
      end_time: '2026-09-12T23:59:00+03:00'
    });
    const out = wUnderTZ('UTC', () => formatWhen(ev, midnight));
    expect(out).toEqual({ text: 'ПОСЛЕДНИЙ ДЕНЬ', urgent: true });
  });

  /** Та же граница у даты конца: 23:59 МСК 20-го — это 20:59 UTC того же дня,
   *  но 21:00 МСК уже уехало бы в UTC на 18:00, и месяц в подписи не должен
   *  зависеть от того, где выполняется код. */
  it('дата конца печатается по МСК', () => {
    const ev = wEv({
      kind: 'running',
      multiday: true,
      actual_start_date: '2026-03-01',
      end_time: '2026-10-01T00:30:00+03:00'
    });
    const out = wUnderTZ('UTC', () => formatWhen(ev, wNow));
    expect(out.text).toBe('ИДЁТ ДО 1 ОКТ');
  });
});
