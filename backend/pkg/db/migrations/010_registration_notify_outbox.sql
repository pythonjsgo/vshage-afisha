-- 010_registration_notify_outbox.sql — надёжная доставка уведомлений о
-- регистрациях в Telegram (директива фаундера 30.08: каждая запись дублируется
-- в чат, «железобетонно, ни одной ошибки»).
--
-- Почему outbox, а не отправка из хендлера: телега бывает недоступна, бэкенд
-- перезапускается деплоем, а запись человека при этом обязана и сохраниться,
-- и доехать уведомлением. Строка outbox пишется В ТОЙ ЖЕ транзакции, что и
-- сама регистрация: либо есть и запись, и уведомление в очереди, либо нет
-- ничего. Отправщик — фоновая горутина: читает неотправленное, шлёт, помечает
-- sent_at; при любой ошибке инкрементит attempts и повторяет на следующем
-- тике — вечно, пока не доедет.
--
-- payload — готовый текст сообщения, собранный в момент записи, когда все
-- поля под рукой (событие, имя, контакт, счётчик мест). Отправщику не нужны
-- JOIN'ы, и удаление события не осиротит уведомление.

CREATE TABLE IF NOT EXISTS registration_notify_outbox (
    id         BIGSERIAL PRIMARY KEY,
    payload    TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    sent_at    TIMESTAMPTZ,
    attempts   INT         NOT NULL DEFAULT 0,
    last_error TEXT
);

-- Частичный: отправщик смотрит только в неотправленное, а таблица со временем
-- почти целиком состоит из отправленного.
CREATE INDEX IF NOT EXISTS idx_reg_notify_unsent
    ON registration_notify_outbox (id) WHERE sent_at IS NULL;
