-- 019_join_requests.sql — анкеты на вход в закрытую сеть (vshage.app/join).
--
-- ЗАЧЕМ. Страница живёт под платным трафиком Яндекс.Директа, то есть каждая
-- строка здесь стоит денег. Отсюда два следствия, которых нет у обычной формы:
--   1) метки кампании (utm_*, yclid) хранятся РЯДОМ с анкетой, а не только в
--      Метрике: Метрика отвечает на «сколько кликов», а на «из какой кампании
--      пришёл человек, которого мы взяли» отвечает только эта таблица;
--   2) referrer/user_agent/ip_hash нужны для разбора накрутки — при платном
--      трафике мусор приходит не «когда-нибудь», а сразу.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ event_registrations. Это не запись на
-- событие: у анкеты нет события, есть решение человека (status). Пришив её к
-- регистрациям, мы бы получили колонку «событие» со значением NULL у целого
-- класса строк и второй смысл у каждого чтения регистраций.
--
-- ТЕЛЕГРАМ ХРАНИМ БЕЗ '@' И В НИЖНЕМ РЕГИСТРЕ — это ключ, по которому
-- считается «анкета уже есть». Отображаемую форму (@Ivanov) собирает
-- читатель; хранить обе — значит однажды разъехаться.
CREATE TABLE IF NOT EXISTS join_requests (
    id               BIGSERIAL PRIMARY KEY,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    name             TEXT NOT NULL,
    -- Канонический код вуза (msu | hse | … | other), а не то, что человек
    -- увидел в списке: подпись переживёт переименование, код — нет.
    university       TEXT NOT NULL,
    -- Заполнено только при university='other'. NULL, а не пустая строка:
    -- «не спрашивали» и «спросили, ответил пусто» — разные факты.
    university_other TEXT,
    course           TEXT NOT NULL,   -- 1..6 | graduate
    about            TEXT NOT NULL,   -- «чем занимаешься», одна строка
    telegram         TEXT NOT NULL,   -- без '@', нижний регистр

    -- Момент согласия на обработку ПД. Хранится ВРЕМЯ, а не булево: доказывать
    -- придётся «когда согласился», и галочка без даты этого не говорит.
    consent_at       TIMESTAMPTZ NOT NULL,

    status           TEXT NOT NULL DEFAULT 'new',
    -- Когда по анкете приняли решение. Отдельно от created_at, потому что
    -- политика конфиденциальности обещает хранить отклонённую заявку «не
    -- дольше 90 дней С ДАТЫ РЕШЕНИЯ»: без этой колонки обещание невозможно
    -- ни выполнить, ни проверить. NULL = ещё не разбирали.
    decided_at       TIMESTAMPTZ,

    utm_source       TEXT,
    utm_medium       TEXT,
    utm_campaign     TEXT,
    utm_content      TEXT,
    utm_term         TEXT,
    yclid            TEXT,
    referrer         TEXT,
    user_agent       TEXT,
    -- Соль общая с веб-регистрацией (WEBREG_IP_SALT). Хеш, а не адрес:
    -- он нужен для «это один и тот же отправитель», а не для опознания.
    ip_hash          TEXT,

    CONSTRAINT join_requests_status_chk
        CHECK (status IN ('new', 'approved', 'rejected'))
);

-- Рабочий разрез модератора: «что новое, сверху свежее». Частичный, потому
-- что со временем таблица почти целиком состоит из уже разобранного.
CREATE INDEX IF NOT EXISTS idx_join_requests_new
    ON join_requests (created_at DESC) WHERE status = 'new';

-- Дедуп «та же анкета за сутки» и разбор накрутки по одному человеку.
-- Уникальным его сделать нельзя: повтор запрещён на 24 часа, а не навсегда —
-- человек, которому отказали в сентябре, имеет право прийти в марте.
CREATE INDEX IF NOT EXISTS idx_join_requests_telegram
    ON join_requests (telegram, created_at DESC);
