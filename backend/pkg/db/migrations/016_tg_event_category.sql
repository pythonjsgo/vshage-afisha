-- 016_tg_event_category.sql — категория карточки из словаря ленты 0.7.
--
-- ЗАЧЕМ. До сих пор категорию tg-карточки лента выводила из `segment` —
-- закрытого перечня ИЗ ШЕСТИ значений (tech, business, culture, sport,
-- social, campus), который пишет vshage-geo/collect/tg_event_cards.py.
-- Словарь ленты 0.7 — СЕМНАДЦАТЬ кодов (network internal/feed/taxonomy.go).
-- Пока источники были студенческие, шести хватало: кампус, спорт, бизнес,
-- тех, культура ложились почти один в один. Городской слой (KudaGo, каналы
-- площадок) в шесть значений не помещается вовсе: концерт, спектакль,
-- экскурсия и вечеринка — все `culture`, то есть все приедут в ленту как
-- `exhibition`. Ранжировщик сравнивает именно по категории, так что это не
-- косметика подписи, а неверная метка под всей персонализацией.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ КОЛОНКА, А НЕ РАСШИРЕНИЕ `segment`. `segment` читают уже
-- три потребителя (лента, витрина сайта, экспортёр), и у него есть свой
-- смысл — «чей это слой», а не «что это за событие». Расширив его, мы бы
-- поменяли смысл существующего поля под живыми читателями: ровно то, что
-- `compatibility.md` запрещает. Колонка добавляется, `segment` остаётся как
-- был и продолжает работать для старых карточек.
--
-- NULL — ЭТО ЗНАЧЕНИЕ, А НЕ ПРОБЕЛ. Он означает «конвейер категорию не
-- прислал», и читатель обязан свалиться на прежний путь (вывод из segment).
-- Поэтому колонка nullable и БЕЗ DEFAULT: любой дефолт задним числом
-- приписал бы 35 живым карточкам категорию, которой у них нет, — та самая
-- ловушка `ticket_mode DEFAULT 'qr'`, уже стоившая нам выданных билетов.
--
-- CHECK не ставится сознательно. Словарь живёт в коде ленты и уже проверяется
-- на границе доверия импорта (internal/tgevents/models.go: feedCategories):
-- ограничение в базе было бы вторым списком тех же значений, который
-- разъедется с первым при следующем пополнении словаря, и разъезд вскроется
-- отказом заливки посреди ночного прогона.
ALTER TABLE afisha_tg_events
    ADD COLUMN IF NOT EXISTS category TEXT;

COMMENT ON COLUMN afisha_tg_events.category IS
    'Код словаря ленты 0.7 (network internal/feed/taxonomy.go). NULL = конвейер не прислал, читатель выводит категорию из segment.';
