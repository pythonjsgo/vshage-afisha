-- 013_registration_mail.sql — письма человеку после записи и за 6 часов до
-- события (директива фаундера 02.09), плюс уведомление организатору в
-- приложение.
--
-- Очередь одна и та же. Телеграм-уведомление организатору, письмо гостю и пуш
-- в приложение отличаются только каналом доставки, а требование к ним общее:
-- пережить недоступность канала и перезапуск бэкенда, не влияя на саму запись.
-- Заводить вторую очередь ради второго канала значило бы копировать
-- отправщик, ретраи и учёт ошибок.
--
-- ОБРАТНАЯ СОВМЕСТИМОСТЬ. channel добавляется с DEFAULT 'tg', поэтому:
--   · все строки, уже лежащие в очереди, остаются телеграм-строками;
--   · триггер webreg_notify_registration() (миграция 011) вставляет только
--     payload и продолжает работать без единой правки;
--   · старый бинарь, выкаченный обратно, читает payload как раньше — он
--     просто не знает про новые колонки.
--
-- Цена отката названа явно: старый отправщик не различает каналы и НЕотправленную
-- строку письма отправит в телеграм-чат как есть, то есть организатор увидит там
-- json письма. Это некрасиво и безвредно; лечится тем же откатом наоборот. Если
-- откат плановый — сначала `UPDATE registration_notify_outbox SET sent_at = NOW()
-- WHERE sent_at IS NULL AND channel <> 'tg'`.
ALTER TABLE registration_notify_outbox
    ADD COLUMN IF NOT EXISTS channel   TEXT NOT NULL DEFAULT 'tg',
    ADD COLUMN IF NOT EXISTS recipient TEXT;

-- Отметки об отправленных письмах живут на самой записи, а не в очереди:
-- очередь чистится и её строки не вечны, а вопрос «письмо этому человеку уже
-- уходило?» задаётся каждую минуту циклом напоминаний. Без этих колонок
-- напоминание уходило бы на каждом тике.
ALTER TABLE event_registrations
    ADD COLUMN IF NOT EXISTS confirm_mail_at  TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS reminder_mail_at TIMESTAMPTZ;

-- Живым записям напоминание НЕ рассылаем задним числом: у события 10.09 уже
-- есть записавшиеся, и включение фичи не должно порождать письмо «через 6
-- часов» тому, кто записался неделю назад, — оно уйдёт ему в свой срок.
-- А вот подтверждение прошлым записям слать поздно и незачем: помечаем их
-- отправленными, чтобы цикл их не подобрал.
UPDATE event_registrations
SET confirm_mail_at = NOW()
WHERE confirm_mail_at IS NULL;

-- Индекс под запрос цикла напоминаний: ищем только то, чему письмо ещё не
-- уходило. Таблица маленькая, но запрос идёт раз в минуту вечно.
CREATE INDEX IF NOT EXISTS idx_event_reg_reminder_pending
    ON event_registrations (event_id) WHERE reminder_mail_at IS NULL;
