-- 009_registration_signup_fields.sql — имя и контакт, которые человек ВПИСАЛ
-- в форму записи на событие.
--
-- До сих пор их негде было хранить: `event_registrations` несёт только
-- event_id + profile_id, а организатор видел имя и почту ПРОФИЛЯ. Для гостя
-- без аккаунта это одно и то же — профиль-пустышка заводится тут же из его
-- ответов. Но у человека, чей контакт уже есть в базе (то есть у живого
-- пользователя Вшаге), запись цепляется к его настоящему профилю, и вписанное
-- имя пропадало совсем: 30.08 фаундер записался как «Александр Суворов», а в
-- списке у организатора стояло «mohammed» — имя его аккаунта.
--
-- Переписывать чужой профиль именем из формы нельзя (это меняет человека в
-- приложении), поэтому вписанное едет отдельными колонками рядом с записью.
--
-- Обе NULLable и без DEFAULT: колонка добавляется к живой таблице, а у уже
-- существующих записей этих данных попросту не было — NULL здесь честнее
-- любого умолчания и читается как «человек записался до этой правки».
-- Читатель (organizer-api) берёт COALESCE(NULLIF(signup_name,''), p.name),
-- поэтому старые строки продолжают показывать имя профиля, как и раньше.

ALTER TABLE event_registrations
    ADD COLUMN IF NOT EXISTS signup_name    TEXT,
    ADD COLUMN IF NOT EXISTS signup_contact TEXT;
