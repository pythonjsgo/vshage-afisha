-- 017_afisha_sources.sql — реестр внешних источников: у индексируемого
-- организатора появляется личность, на которую можно подписаться.
--
-- ЗАЧЕМ. Сегодня «сообщество» события — это `tg:<slug(org_name)>`, где
-- `org_name` пишет модель по каждому посту отдельно. Замер 05.09 на DEV:
-- 169 карточек — 116 разных имён организатора; у одного канала
-- (`ranepasport`) шесть карточек и шесть разных «организаторов». Подписка на
-- такого орга не работает по построению: завтра он станет другим, а строка в
-- `community_follows` будет указывать в никуда, ничего никому не сообщив.
--
-- Ключ теперь — АДРЕС, ПО КОТОРОМУ МЫ ЧИТАЕМ, а не имя, которое кто-то
-- написал: `tg:<handle>`, `vk:<handle>`, `kudago:place:<id>`. Он стабилен
-- ровно потому, что совпадает с ключом в реестре источников конвейера
-- (vshage-geo/collect/sources.jsonl), и меняется только вместе с ним.
--
-- ПОЧЕМУ У АГРЕГАТОРА ОРГАНИЗАТОР — НЕ АГРЕГАТОР. У KudaGo один handle на
-- 124 карточки и 80 разных площадок. Организатор там — площадка, у неё есть
-- стабильный внешний id, и ключ строится по нему. Иначе «подписаться на
-- организатора» подписало бы человека на весь городской агрегатор разом.
--
-- ПОЧЕМУ СЕЙЧАС. Подписок в базе одна на DEV и ноль на проде — смена формата
-- ключа не стоит ничего. Через неделю с партнёрами это стало бы переносом
-- чужих подписок руками.
--
-- ДАННЫЕ РЕЕСТРА УЖЕ СОБРАНЫ и никогда не доезжали до продукта:
-- `events/tg_channels.jsonl` в корпусе — 132 карточки каналов с названием,
-- описанием, числом подписчиков, вузом, кампусами, рубриками и статистикой
-- постов. Эта таблица — их витрина, а не второй реестр.
CREATE TABLE IF NOT EXISTS afisha_sources (
    -- key — то же, что `community_follows.community` в core-api: подписка
    -- пишется на эту строку и обязана её пережить.
    key        TEXT PRIMARY KEY,
    platform   TEXT NOT NULL,          -- tg | vk | api
    handle     TEXT NOT NULL,
    title      TEXT NOT NULL,
    url        TEXT,
    descr      TEXT,
    subs       INTEGER,                -- подписчиков у первоисточника, если знаем
    kind       TEXT,                   -- university_official | venue | aggregator | community
    university TEXT,
    segments   JSONB,                  -- рубрика → сколько постов (из карточки канала)
    stats      JSONB,                  -- posts / first / last / days_silent
    flags      JSONB,
    -- enabled=false — отзыв источника владельцем. Читатели ленты его НЕ
    -- смотрят: гасит карточки экспорт, ставя им hidden. Один писатель меняет
    -- строки, читатели остаются как есть — то же правило, по которому сделана
    -- отложенная публикация (03.09). Джойн на горячем пути ленты стоил бы
    -- дороже и разъехался бы с витриной сайта.
    enabled    BOOLEAN NOT NULL DEFAULT TRUE,
    -- claimed_by — кабинет, забравший источник себе (claim v1, отдельная
    -- задача). TEXT без внешнего ключа СОЗНАТЕЛЬНО, по той же причине, по
    -- которой `event_intents.event_ref` не FK: таблицей владеет афиша, а
    -- профилями — core-api, и жёсткая связь между сервисами ломала бы
    -- независимый деплой.
    claimed_by TEXT,
    -- Логотип байтами, а не ссылкой: аватар t.me живёт на их CDN и протухает
    -- за дни (это уже ловили на обложках постов). Отдаётся своим эндпоинтом.
    logo       BYTEA,
    logo_mime  TEXT,
    imported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE afisha_sources IS
    'Внешние сообщества и площадки, события которых мы индексируем. key = адрес чтения (tg:<handle> | vk:<handle> | kudago:place:<id>) и он же ключ подписки в community_follows.';

-- Связь карточки с реестром — ключом, а не текстом. `org_name` остаётся
-- отображаемым именем (оно человеческое и может меняться), личность живёт
-- отдельно и от него не зависит.
ALTER TABLE afisha_tg_events
    ADD COLUMN IF NOT EXISTS source_key TEXT;

COMMENT ON COLUMN afisha_tg_events.source_key IS
    'Ключ строки afisha_sources. NULL = карточка старше реестра, читатель выводит сообщество из org_name по-прежнему.';

-- Частичный: карточек без ключа со временем не останется, а пока их
-- большинство, полный индекс был бы вдвое больше нужного.
CREATE INDEX IF NOT EXISTS idx_afisha_tg_events_source_key
    ON afisha_tg_events (source_key) WHERE source_key IS NOT NULL;
