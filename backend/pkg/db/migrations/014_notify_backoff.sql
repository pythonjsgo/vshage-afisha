-- 014_notify_backoff.sql — пауза между попытками доставки.
--
-- До неё отправщик долбил упавший канал каждые 10 секунд вечно. На стенде это
-- видно сразу (телеграм там не настроен, и лог за минуту наполняется шестью
-- одинаковыми строками), а на бою обернулось бы восемью тысячами обращений в
-- сутки к чужому API, который и так лежит, — и логом, в котором из-за этого не
-- видно ничего другого.
--
-- Пауза растёт с числом попыток и упирается в потолок: доставка обязана
-- дождаться починки канала, а не сдаться, поэтому «бросить строку после N
-- попыток» здесь неправильный ответ.
--
-- NULL означает «можно сейчас» — все уже лежащие строки остаются к отправке
-- готовыми, и добавление колонки ничего не задерживает.
ALTER TABLE registration_notify_outbox
    ADD COLUMN IF NOT EXISTS next_attempt_at TIMESTAMPTZ;
