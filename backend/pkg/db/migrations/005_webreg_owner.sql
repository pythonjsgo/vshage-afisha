-- Владелец веб-события: кабинет организатора, который его завёл.
--
-- До сих пор конфиг события был чисто админской поверхностью — один список на
-- всех. Как только экран отдаётся организатору (Юлия заводит свои события
-- сама), «один список на всех» означает, что он видит и правит чужое, включая
-- ивент, который идёт завтра. Поэтому у события появляется владелец, а список
-- фильтруется по нему.
--
-- NULL — намеренно: так помечены события, заведённые ДО этой миграции
-- (платформенные, ШАГ в их числе). Их по-прежнему видит только админ, и ни
-- один организатор не получит на них прав задним числом.
--
-- Чего здесь СОЗНАТЕЛЬНО нет: способа передать событие. Владелец проставляется
-- один раз, при создании, из кабинета создающего; админ создаёт событие без
-- владельца и «отдать его Юле» из интерфейса нельзя — только UPDATE руками по
-- живой таблице. Как только такая просьба прозвучит второй раз, это повод
-- сделать передачу нормальной операцией, а не искать этот комментарий.
ALTER TABLE webreg_events
    ADD COLUMN IF NOT EXISTS owner_slug TEXT;

CREATE INDEX IF NOT EXISTS idx_webreg_events_owner
    ON webreg_events (owner_slug)
    WHERE owner_slug IS NOT NULL;
