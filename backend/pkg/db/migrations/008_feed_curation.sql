-- 008_feed_curation.sql — кураторские колонки витрины tg-событий: гео места
-- и два флага полок ленты приложения (лента v2, issue network#364).
--
-- venue — гео-обвязка места (координаты, метро), которую проставляет курация,
-- а не импорт. JSONB, а не три колонки: состав полей ещё меняется, а таблица
-- публичная поверхность — каждое новое поле стоило бы миграции и правки
-- апсерта. Наружу из него едут ровно lat/lon/metro (см. internal/tgevents).
--
-- feed/anchor — что показывать в ленте приложения: feed = карточка допущена
-- на полку, anchor = она же «событие недели». Умолчание FALSE единственное
-- безопасное: импорт наливает карточки пачками, и любое другое раздало бы
-- непросмотренную витрину людям. NOT NULL DEFAULT на новой колонке здесь
-- допустим сознательно — таблица десятки строк, PG11+ пишет дефолт в каталог
-- и страницы не переписывает, а живые строки получают ровно то же значение,
-- что и новые (то есть явный UPDATE не нужен: смысла «было иначе» тут нет).
--
-- КРИТИЧНО для импорта: ни одна из трёх колонок НЕ входит в ON CONFLICT DO
-- UPDATE в repository.go — по той же причине, по какой там нет hidden.
-- Кураторское решение не должно откатываться следующей заливкой партии.

ALTER TABLE afisha_tg_events
    ADD COLUMN IF NOT EXISTS venue  JSONB,
    ADD COLUMN IF NOT EXISTS feed   BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS anchor BOOLEAN NOT NULL DEFAULT FALSE;

-- Витрина ленты приложения читается core-api НАПРЯМУЮ из этой таблицы
-- (read-only SELECT) ровно этим предикатом: допущено, не снято, не прошло.
-- Индекс частичный по той же причине, что и idx_afisha_tg_events_upcoming
-- из 006: витрина — малая доля таблицы.
CREATE INDEX IF NOT EXISTS idx_afisha_tg_events_feed
    ON afisha_tg_events (date) WHERE feed AND NOT hidden;
