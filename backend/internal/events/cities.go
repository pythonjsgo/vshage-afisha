package events

import "strings"

// City — город доски. Падежи едут ГОТОВЫМИ строками, а не выводятся правилом:
// русское склонение исключений не прощает («в Москве», но «во Владимире»,
// «в Нижнем Новгороде»), и правило, написанное по одному городу, ломается на
// втором молча — в заголовке страницы и в title, то есть ровно там, где текст
// читает поисковик, а не человек, который мог бы пожаловаться.
type City struct {
	Slug string `json:"slug"`
	Name string `json:"name"` // именительный: «Москва»
	In   string `json:"in"`   // предложный с предлогом: «в Москве»
	Of   string `json:"of"`   // родительный: «Москвы»
}

// cities — весь словарь доски. Сегодня город ОДИН, и это не повод не
// фильтровать: карточки приезжают из внешних конвейеров (KudaGo, каналы
// площадок), и первый же питерский адрес в выдаче попал бы на московскую
// доску молча — заметил бы это человек, приехавший не туда, а не прибор.
//
// Порядок словаря — порядок показа в переключателе города. Второй город
// добавляется ЗДЕСЬ и приезжает во все три поверхности сразу (лента, фасеты,
// адреса), потому что источник у них один.
var cities = []City{
	{Slug: "msk", Name: "Москва", In: "в Москве", Of: "Москвы"},
}

// DefaultCitySlug — город, который открывается без явного выбора и на который
// записываются карточки без города. См. StoreSQL.CityExpr: «города нет» — это
// не «другой город», это неизвестность, и оставлять её вне доски значило бы
// прятать живые события из-за незаполненного поля формы.
const DefaultCitySlug = "msk"

// Cities возвращает словарь целиком (копию: словарь общий на процесс).
func Cities() []City {
	out := make([]City, len(cities))
	copy(out, cities)
	return out
}

// CityBySlug — город по слагу. Второе значение false означает «такого города
// нет», и вызывающий обязан ответить отказом, а не молча взять Москву:
// подмена города на дефолтный делает неверный адрес неотличимым от верного.
func CityBySlug(slug string) (City, bool) {
	slug = strings.ToLower(strings.TrimSpace(slug))
	for _, c := range cities {
		if c.Slug == slug {
			return c, true
		}
	}
	return City{}, false
}

// DefaultCity — город по умолчанию. Отсутствие его в словаре — дефект сборки,
// а не рантайм-ситуация, поэтому здесь нет второго возврата: словарь и
// константа правятся одной строкой ниже друг друга.
func DefaultCity() City {
	c, ok := CityBySlug(DefaultCitySlug)
	if !ok {
		// Недостижимо, пока словарь и константа согласованы; вернуть пустой
		// город безопаснее паники — доска отдаст «фильтра по городу нет».
		return City{}
	}
	return c
}
